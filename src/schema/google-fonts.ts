export function searchGoogleFonts(query: string) {
  const q = query.trim().toLowerCase()
  if (!q) return GOOGLE_FONTS_CATALOG
  return GOOGLE_FONTS_CATALOG.filter(
    (f) => f.family.toLowerCase().includes(q) || f.category.includes(q),
  )
}
